export function localeForLanguage(language: AppLanguage): string {
  switch (language) {
    case "en":
      return "en-US";
    case "ja":
      return "ja-JP";
    case "ko":
    default:
      return "ko-KR";
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(DEFAULT_LANGUAGE);

  useEffect(() => {
    let cancelled = false;
    settingsApi.get()
      .then((settings) => {
        if (!cancelled) setLanguageState(normalizeLanguage(settings.language));
      })
      .catch(() => {
        if (!cancelled) setLanguageState(DEFAULT_LANGUAGE);
      });
    return () => { cancelled = true; };
  }, []);

  const setLanguage = useCallback((next: AppLanguage) => {
    setLanguageState(normalizeLanguage(next));
  }, []);

  const t = useCallback<I18nContextValue["t"]>(
    (key, values) => translate(language, key, values),
    [language],
  );

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}
