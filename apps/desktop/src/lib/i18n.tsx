export function formatWordCount(language: AppLanguage, words: number): string {
  if (words === 0) return translate(language, "project.words.empty");
  if (words < 10_000) {
    return translate(language, "project.words.count", {
      count: words.toLocaleString(localeForLanguage(language)),
    });
  }
  return translate(language, "project.words.compact", {
    count: (words / 1000).toFixed(0),
  });
}

