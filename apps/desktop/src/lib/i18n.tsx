interface I18nContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function normalizeLanguage(value: unknown): AppLanguage {
  return APP_LANGUAGES.some((lang) => lang.value === value) ? value as AppLanguage : DEFAULT_LANGUAGE;
}

export function translate(language: AppLanguage, key: MessageKey, values: Record<string, string | number> = {}) {
  const template = messages[language][key] ?? messages[DEFAULT_LANGUAGE][key] ?? key;
  return Object.entries(values).reduce(
    (out, [name, value]) => out.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function lengthLabel(language: AppLanguage, value: LengthTarget): string {
  return translate(language, `project.length.${value}` as MessageKey);
}

export function povLabel(language: AppLanguage, value: DefaultPOV): string {
  if (value === "third_limited") return translate(language, "project.pov.thirdLimited");
  return translate(language, `project.pov.${value}` as MessageKey);
}

export function toneLabel(language: AppLanguage, value: ToneID): string {
  return translate(language, `ai.tone.${value}` as MessageKey);
}

export function displayNodeLabel(language: AppLanguage, label: string): string {
  const trimmed = label.trim();
  const scene = trimmed.match(/^(?:씬|Scene|シーン)\s+(\d+)$/i);
  if (scene) return translate(language, "workspace.sceneNumber", { number: scene[1] });
  const chapter = trimmed.match(/^(?:(\d+)장|Chapter\s+(\d+)|第(\d+)章)$/i);
  if (chapter) {
    return translate(language, "workspace.chapterNumber", {
      number: chapter[1] ?? chapter[2] ?? chapter[3] ?? "",
    });
  }
  return label;
}

